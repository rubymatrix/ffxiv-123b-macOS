def luajit(env, uwp):
    """LuaJIT as a static library (with our parser patch, Lua 5.2 compatibility), built by its own
    msvcbuild.bat in a copy of third_party/luajit. The UWP app's has the dynamic CRT and no JIT: a
    packaged app without the codeGeneration capability may not make executable memory."""
    work = os.path.join(ROOT, 'build', 'third_party', 'luajit-uwp' if uwp else 'luajit-win')
    lib = os.path.join(work, 'src', 'lua51.lib')
    src_tree = os.path.join(ROOT, 'third_party', 'luajit')
    newest = max(os.path.getmtime(os.path.join(d, f)) for d, _, fs in os.walk(src_tree) for f in fs)
    if os.path.exists(lib) and os.path.getmtime(lib) >= newest:
        return lib
    if os.path.exists(work):
        shutil.rmtree(work)
    shutil.copytree(src_tree, work)
    bat = os.path.join(work, 'src', 'msvcbuild.bat')
    text = open(bat).read()
    extra = ' /MD /DLUAJIT_DISABLE_JIT' if uwp else ' /MT'
    text = text.replace('@set LJCOMPILE=cl /nologo /c /O2 /W3', '@set LJCOMPILE=cl /nologo /c /O2 /W3' + extra, 1)
    open(bat, 'w').write(text)
    print('> msvcbuild.bat lua52compat static (%s)' % ('uwp' if uwp else 'win'))
    subprocess.check_call(['cmd', '/c', 'msvcbuild.bat', 'lua52compat', 'static'], cwd=os.path.join(work, 'src'), env=env)
    return lib


def addon_objects(env, cflags, objdir, uwp=False):
    """The addon host's objects and LuaJIT's library, compiled with the host's C flags (C++: the same
    runtime, C++17)."""
    run([sys.executable, 'tools/embed_lua.py'])
    names = sorted(os.listdir(ADDON_DIR))
    c = ['host\\addons\\' + f for f in names if f.endswith('.c')] + ['generated\\addons_lua.c']
    cpp = ['host\\addons\\' + f for f in names if f.endswith('.cpp')]
    sdl_inc = ['/I', os.path.join(SDL3, 'include')]
    cxx = [f for f in cflags if f != '/std:c11'] + ['/std:c++17', '/EHsc', '/Zc:__cplusplus']
    objs = compile_stale(env, c, objdir + '\\addons', ADDON_INCLUDES + sdl_inc + HOST_INCLUDES + ['/I', 'runtime\\portable'], cflags)
    objs += compile_stale(env, cpp, objdir + '\\addons_cpp', ADDON_INCLUDES + sdl_inc + HOST_INCLUDES + ['/I', 'runtime\\portable'], cxx)
    objs += compile_stale(env, IMGUI, objdir + '\\imgui', ADDON_INCLUDES, cxx)
    objs += compile_stale(env, LUASOCKET, objdir + '\\luasocket', ADDON_INCLUDES, cflags)
    objs += compile_stale(env, ['third_party\\lfs\\lfs.c'], objdir + '\\lfs', ADDON_INCLUDES, cflags)
    # SQLite and its Lua binding (Windower's sqlite3 module)
    objs += compile_stale(env, ['third_party\\sqlite\\sqlite3.c', 'third_party\\sqlite\\lsqlite3\\lsqlite3.c'], objdir + '\\sqlite',
                          ADDON_INCLUDES + ['/I', 'third_party\\sqlite', '/DSQLITE_THREADSAFE=0', '/DSQLITE_OMIT_LOAD_EXTENSION'], cflags)
    return objs + [luajit(env, uwp)]


def sdl3():
    """SDL3's include flags and import library."""
    if not os.path.exists(os.path.join(SDL3, 'include', 'SDL3', 'SDL.h')):
        raise SystemExit('SDL3 not found at %s: unpack SDL3-devel-<version>-VC.zip there, or set SDL3_DIR' % SDL3)
    return ['/I', os.path.join(SDL3, 'include')], os.path.join(SDL3, 'lib', 'x64', 'SDL3.lib')


def translate():
    """FFXiMain and FFXi.dll translated to C (only the files whose text changed are rewritten)."""
    recomp('generated/all', ['--all'])
    run([sys.executable, 'recomp/recomp.py', '--meta', FFXI_META, '--image', FFXI_IMAGE, '--retail',
         FFXI_RETAIL, '--module', 'ffxi', '--out', 'generated/ffxi', '--all'])


def game_objects(env):
    """FFXiMain and FFXi.dll translated and compiled: the objects every 64-bit host links."""
    translate()
    gen = ['generated\\all\\' + f for f in sorted(os.listdir(os.path.join(ROOT, 'generated', 'all'))) if f.endswith('.c')]
    gen_ffxi = ['generated\\ffxi\\' + f for f in sorted(os.listdir(os.path.join(ROOT, 'generated', 'ffxi'))) if f.endswith('.c')]
    objs = compile_stale(env, gen, 'build\\all64', ['/I', 'generated\\all'], CFLAGS64)
    objs += compile_stale(env, gen_ffxi, 'build\\ffxi64', ['/I', 'generated\\ffxi'], CFLAGS64)
    return objs


def host64(env):
    """The 64-bit game host: FFXiMain and FFXi.dll translated, the portable runtime, SDL3."""
    objs = game_objects(env)
    sdl_inc, sdl_lib = sdl3()
    objs += compile_stale(env, PORTABLE + HOST_SOURCES, 'build\\host64', sdl_inc + HOST_INCLUDES, CFLAGS64)
    objs += addon_objects(env, CFLAGS64, 'build\\host64')
    # Addons' ffi.C looks in the exe's own exports first, then the CRT, kernel32, user32 and gdi32: the
    # D3DX and gdifonts stand-ins (host/addons/d3d_ffi.c, gdifont_ffi.c) are __declspec(dllexport), so
    # host64.exe exports them (link also writes an import .lib/.exp nobody needs). Win32 functions are the
    # real ones (win32_ffi.c is empty on Windows); ones in other DLLs (winmm's PlaySound, shell32) need
    # xi.lua to ffi.load the real DLL there rather than map it to ffi.C.
    run(['link', '/nologo', '/OUT:build\\host64.exe', '/MACHINE:X64', sdl_lib] + HOST_LIBS + objs, env)
    shutil.copy(os.path.join(SDL3, 'lib', 'x64', 'SDL3.dll'), os.path.join(ROOT, 'build'))
    print('built build\\host64.exe; run: build\\host64.exe --game "%s" ...' % BUILD['game'])


def host64_headless(env):
    """host64 with the null graphics back end: nothing drawn, the frame profile kept (FFXI_PROFILE=1)."""
    objs = game_objects(env)
    sdl_inc, sdl_lib = sdl3()
    objs += compile_stale(env, PORTABLE + HOST_BASE + ['runtime\\portable\\gfx_null.c'], 'build\\headless', sdl_inc + HOST_INCLUDES,
                          CFLAGS64)
    libs = [lib for lib in HOST_LIBS if lib not in GFX_LIBS]
    run(['link', '/nologo', '/OUT:build\\host64-headless.exe', '/MACHINE:X64', sdl_lib] + libs + objs, env)
    shutil.copy(os.path.join(SDL3, 'lib', 'x64', 'SDL3.dll'), os.path.join(ROOT, 'build'))
    print('built build\\host64-headless.exe')


# The UWP app (FFXIXbox) links the game as a library: the dynamic CRT (/MD) that UWP apps must use, no
# SDL3 (sdl_uwp.c in its place; SDL3's headers still give the types), the sign-in's TLS from the app,
# and host64's main renamed host_main for the app to call. Which Win32 calls UWP allows is checked
# when the app links, against WindowsApp.lib alone.
UWP_CFLAGS = [f for f in CFLAGS64 if f != '/MT'] + ['/MD', '/DFFXI_UWP']


def uwp_lib(env):
    """build/uwp/ffxi_uwp.lib: host64 for the UWP app, drawing with Direct3D 12 into its SwapChainPanel."""
    translate()
    gen = ['generated\\all\\' + f for f in sorted(os.listdir(os.path.join(ROOT, 'generated', 'all'))) if f.endswith('.c')]
    gen_ffxi = ['generated\\ffxi\\' + f for f in sorted(os.listdir(os.path.join(ROOT, 'generated', 'ffxi'))) if f.endswith('.c')]
    objs = compile_stale(env, gen, 'build\\uwp\\all', ['/I', 'generated\\all'], UWP_CFLAGS)
    objs += compile_stale(env, gen_ffxi, 'build\\uwp\\ffxi', ['/I', 'generated\\ffxi'], UWP_CFLAGS)
    sdl_inc = ['/I', os.path.join(SDL3, 'include')]
    # the app signs in itself (its own login screen): no sign-in screen
    host = [s for s in HOST_SOURCES if s not in SIGNIN_SCREEN] + ['host\\signin_none.c', 'runtime\\portable\\sdl_uwp.c']
    objs += compile_stale(env, PORTABLE + host, 'build\\uwp\\host', sdl_inc + ['/Dmain=host_main'], UWP_CFLAGS)
    objs += addon_objects(env, UWP_CFLAGS, 'build\\uwp', uwp=True)
    run(['lib', '/nologo', '/OUT:build\\uwp\\ffxi_uwp.lib'] + objs, env)
    print('built build\\uwp\\ffxi_uwp.lib')


