def write_build_h():
    """generated/build.h: the addresses of this build that the runtime and tests name directly."""
    lines = ['/* Generated by tools/build.py from meta/builds.json. Do not edit. */', '#pragma once',
             '#define FFXI_BUILD "%s"' % BUILD['build'],
             '#define FFXI_VERSION "%s" /* the version string patch.ver carries */' % BUILD['version']]
    for k, v in BUILD['addresses'].items():
        lines.append('#define FFXI_%s 0x%08xu' % (k.upper(), int(v, 16)))
    for k, v in BUILD['hooks'].items():
        lines.append('#define FFXI_HOOK_%s 0x%08xu /* rt_hook_%s runs here */' % (k.upper(), int(v, 16), k))
    for k, v in BUILD['wraps'].items():
        lines.append('#define FFXI_WRAP_%s 0x%08xu /* rt_wrap_%s may replace this function */' % (k.upper(), int(v, 16), k))
    for k, v in BUILD['crt'].items():
        a = int(v, 16)
        lines.append('#define CRT_%s 0x%08xu' % (k.upper(), a))
        lines.append('#define F_%s f_%08x' % (k.upper(), a))
    # host/modern.c's addresses: FFXI_MODERN is 1 only when this build has every one of them (a
    # build carried without them, or with one unmapped, gets 0 and every address 0: not called).
    modern = BUILD['modern']
    whole = bool(BUILD['modern_keys']) and all(modern.get(k, '').startswith('0x') for k in BUILD['modern_keys'])
    lines.append('#define FFXI_MODERN %d /* Config > Modern and Config > Menus */' % whole)
    for k in BUILD['modern_keys']:
        lines.append('#define FFXI_MODERN_%s 0x%08xu' % (k.upper(), int(modern[k], 16) if whole else 0))
    text = '\n'.join(lines) + '\n'
    try:
        with open(BUILD_H) as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(BUILD_H, 'w') as f:
        f.write(text)


