def main():
    what = sys.argv[1] if len(sys.argv) > 1 else 'difftest'
    targets = {'difftest': difftest, 'host': host, 'boot64': boot64, 'host64': host64,
               'host64-headless': host64_headless, 'uwp-lib': uwp_lib, 'gfxtest': gfxtest}
